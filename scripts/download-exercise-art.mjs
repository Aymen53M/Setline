import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const imageRoot = path.join(root, "assets", "images", "repdb");
const rawRoot = "https://raw.githubusercontent.com/RepDB/exercise-dataset/main/";
const exercises = {
  "incline-dumbbell-press": "incline-db-press",
  "seated-shoulder-press": "machine-shoulder-press",
  "pec-deck": "pec-deck",
  "push-cable-lateral-raise": "cable-lateral-raise",
  "push-overhead-cable-triceps-extension": "cable-overhead-tricep-extension",
  "push-leg-extension": "leg-extension",
  "lat-pulldown": "lat-pulldown",
  "chest-supported-row": "chest-supported-machine-row",
  "incline-dumbbell-curl": "incline-db-curl",
  "reverse-pec-deck-rear-delt-fly": "machine-reverse-fly",
  "pull-forward-lean-seated-leg-curl": "seated-leg-curl",
  "leg-press": "leg-press",
  "romanian-deadlift": "dumbbell-romanian-deadlift",
  "lower-leg-extension-3s-eccentric": "leg-extension",
  "seated-leg-curl": "seated-leg-curl",
  "lower-hip-abduction": "hip-abduction",
  "standing-calf-raises": "standing-calf-raise",
  "cable-crunches": "cable-crunch",
  "machine-chest-press": "chest-press-machine",
  "upper-close-neutral-grip-pulldown": "close-grip-lat-pulldown",
  "upper-cable-lateral-raise": "cable-lateral-raise",
  "upper-wide-grip-seated-cable-row": "wide-grip-seated-cable-row",
  "upper-cable-ez-bar-curl": "cable-curl",
  "upper-overhead-triceps-extension": "cable-overhead-tricep-extension",
  "upper-cable-crunch": "cable-crunch",
};

const response = await fetch(`${rawRoot}exercises.json`);
if (!response.ok) throw new Error(`RepDB index returned HTTP ${response.status}`);
const catalog = (await response.json()).exercises;
const byId = new Map(catalog.map((exercise) => [exercise.id, exercise]));
const selected = Object.fromEntries(Object.entries(exercises).map(([appId, repdbId]) => {
  const exercise = byId.get(repdbId);
  if (!exercise) throw new Error(`RepDB exercise not found: ${repdbId}`);
  return [appId, exercise];
}));

async function download(source, destination) {
  await mkdir(path.dirname(destination), { recursive: true });
  const result = await fetch(`${rawRoot}${source}`);
  if (!result.ok) throw new Error(`Could not download ${source}: HTTP ${result.status}`);
  await writeFile(destination, new Uint8Array(await result.arrayBuffer()));
}

const downloaded = new Set();
for (const exercise of Object.values(selected)) {
  for (const pose of ["start", "peak"]) {
    const imagePath = exercise.images.flat[pose];
    if (!imagePath || downloaded.has(imagePath)) continue;
    downloaded.add(imagePath);
    await download(imagePath, path.join(imageRoot, "exercises", path.basename(imagePath)));
  }
}

const muscleIds = [...new Set(Object.values(selected).flatMap((exercise) => [
  ...(exercise.primary_muscles ?? []),
  ...(exercise.secondary_muscles ?? []),
]))].sort();
for (const muscleId of muscleIds) {
  const imageName = `${muscleId.replaceAll("_", "-")}.webp`;
  await download(`images/muscles/${imageName}`, path.join(imageRoot, "muscles", imageName));
}

const muscleSource = Object.fromEntries(muscleIds.map((muscleId) => [
  muscleId,
  `__require__(../assets/images/repdb/muscles/${muscleId.replaceAll("_", "-")}.webp)`,
]));
const exerciseSource = Object.fromEntries(Object.entries(selected).map(([appId, exercise]) => {
  return [appId, {
    sourceId: exercise.id,
    start: imageSource(exercise, "start"),
    finish: imageSource(exercise, "peak"),
    primaryMuscles: exercise.primary_muscles ?? [],
    secondaryMuscles: exercise.secondary_muscles ?? [],
  }];
  function imageSource(record, pose) {
    const source = record.images.flat[pose];
    return source ? `__require__(../assets/images/repdb/exercises/${path.basename(source)})` : undefined;
  }
}));

const moduleSource = [
  "// Generated by scripts/download-exercise-art.mjs. Media and muscle illustrations are credited in assets/images/REPDB_CREDITS.md.",
  "",
  "export type MuscleArt = { id: string; label: string; image: number };",
  "export type ExerciseArt = { sourceId: string; start: number; finish: number; primaryMuscles: string[]; secondaryMuscles: string[] };",
  "",
  `const MUSCLE_IMAGES: Record<string, number> = ${JSON.stringify(muscleSource, null, 2).replaceAll(/"__require__\(([^)]+)\)"/g, 'require("$1")')};`,
  "",
  `export const EXERCISE_ART: Record<string, ExerciseArt> = ${JSON.stringify(exerciseSource, null, 2).replaceAll(/"__require__\(([^)]+)\)"/g, 'require("$1")')};`,
  "",
  "export const formatMuscleName = (id: string) => id.split(\"_\").map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(\" \");",
  "export const muscleArt = (id: string): MuscleArt | undefined => MUSCLE_IMAGES[id] ? { id, label: formatMuscleName(id), image: MUSCLE_IMAGES[id] } : undefined;",
  "",
].join("\n");

await writeFile(path.join(root, "lib", "exercise-art.generated.ts"), moduleSource);
console.log(`Downloaded ${downloaded.size} exercise poses and ${muscleIds.length} target-muscle illustrations.`);
